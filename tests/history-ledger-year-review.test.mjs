import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {historyLedgerRows,historyYearSummary} from '../public/archive/history-ledger-model.mjs';

const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const races=[
 {id:'E-1953-A',year:1953,date:'1953-05-02',name:'Kentucky Derby',track_name:'Churchill Downs',date_basis:'HISTORICAL_EXACT_DATE',status:'RECORDED'},
 {id:'E-1953-B',year:1953,date:null,name:'Preakness Stakes',track_name:'Pimlico',status:'RECORDED'},
 {id:'E-1953-C',year:1953,date:'1953-06-02',name:'Belmont Stakes',track_name:'Belmont Park',status:'RECORDED'},
 {id:'E-1952-A',year:1952,date:'1952-05-03',name:'Kentucky Derby',track_name:'Churchill Downs',status:'RECORDED'},
 {id:'E-1954-A',year:1954,date:null,name:'Kentucky Oaks',track_name:'Churchill Downs',status:'RECORDED'},
 {id:'E-1954-HOLD',year:1954,name:'Held race',track_name:'Test',status:'QUARANTINED_SOURCE'},
 {id:'E-1953-D',year:1953,date:null,name:'No verified results',track_name:'Pimlico',status:'RECORDED'}
];
const winners=new Map([
 ['E-1953-A',{horse_id:'H-1950-001',name:'Classic Winner'}],
 ['E-1953-B',{horse_id:'H-1950-001',name:'Classic Winner'}],
 ['E-1953-C',{horse_id:'H-1950-002',name:'Other Winner'}],
 ['E-1952-A',{horse_id:'H-1949-001',name:'Older Winner'}]
]);

test('single history ledger includes all loaded historical years, stable default year DESC, no held editions',()=>{
 const frozen=JSON.stringify(races);
 const rows=historyLedgerRows(races,winners);
 assert.equal(rows.length,6);
 assert.deepEqual(rows.map(x=>x.year),[1954,1953,1953,1953,1953,1952]);
 assert.ok(!rows.some(x=>x.id==='E-1954-HOLD'));
 assert.equal(JSON.stringify(races),frozen,'Rendering/sorting must never mutate historical canon');
 assert.equal(rows.find(x=>x.id==='E-1953-A').winnerId,'H-1950-001');
});

test('all sortable history columns correctly reverse, missing dates and winners remain last',()=>{
 const byName=historyLedgerRows(races,winners,{sort:'race',desc:false});
 const reversed=historyLedgerRows(races,winners,{sort:'race',desc:true});
 assert.equal(byName[0].race,'Belmont Stakes');
 assert.equal(reversed[0].race,'Preakness Stakes');
 const years=historyLedgerRows(races,winners,{sort:'year',desc:false});
 assert.equal(years[0].year,1952);
 const winnerSort=historyLedgerRows(races,winners,{sort:'winner',desc:true});
 assert.deepEqual(winnerSort.slice(-2).map(x=>x.winner),['','']);
 const dates=historyLedgerRows(races,winners,{sort:'date',desc:false});
 assert.ok(dates.slice(-3).every(x=>!x.date));
 const evidence=historyLedgerRows(races,winners,{sort:'evidence',evidenceFor:r=>r.date_basis||'No exact date'});
 assert.equal(evidence.length,6);
});

test('year/track/search filters apply to full loaded source, including winner, horse ID and edition ID',()=>{
 assert.equal(historyLedgerRows(races,winners,{year:1953}).length,4);
 assert.equal(historyLedgerRows(races,winners,{track:'Pimlico'}).length,2);
 assert.equal(historyLedgerRows(races,winners,{query:'H-1950-001'}).length,2);
 assert.equal(historyLedgerRows(races,winners,{query:'e-1953-a'}).length,1);
 assert.equal(historyLedgerRows(races,winners,{query:'Belmont'}).length,1);
 assert.equal(historyLedgerRows(races,winners,{year:1953,track:'Pimlico',query:'Preakness'}).length,1);
});

test('Year in Review shows only recorded Classic winners; no invented winners or inferred championships',()=>{
 const summary=historyYearSummary(1953,races,winners);
 assert.equal(summary.rows.length,4);
 assert.deepEqual(summary.classics.map(x=>x.row?.winner||null),['Classic Winner','Classic Winner','Other Winner']);
 assert.equal(summary.recordedWinners,3);
 assert.deepEqual(summary.mostRecordedWins.map(x=>[x.name,x.wins]),[['Classic Winner',2],['Other Winner',1]]);
 assert.deepEqual(summary.verifiedAwards,[]);
 assert.equal(historyYearSummary(1954,races,winners).classics[0].row,null,
  'Missing Classic edition must remain missing, not be autogenerated');
});

test('Annual awards are displayed only from an explicitly verified, keyed source',()=>{
 const raw=[
  {year:1953,category:'Horse of the Year',winner_name:'Unverified Winner',source_id:'AW-1',status:'DRAFT'},
  {year:1953,category:'Champion 3YO',winner_name:'Source Winner',source_id:'AW-2',status:'SOURCE_VERIFIED',source:'Eclipse audit'},
  {year:1953,category:'Champion Male',winner_name:'No source ID',status:'VERIFIED'},
  {year:1952,category:'Earlier Champion',winner_name:'Other Year',source_id:'AW-3',status:'VERIFIED'}
 ];
 const summary=historyYearSummary(1953,races,winners,raw);
 assert.deepEqual(summary.verifiedAwards.map(x=>x.sourceId),['AW-2']);
 assert.equal(historyYearSummary(1953,races,winners).verifiedAwards.length,0);
});

