import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const page=read('public/next/facility-workspace-preview.html');
const dir=JSON.parse(read('public/data/wtw-1999-founding-directory-v1.json'));
const geo=JSON.parse(read('public/data/track-geography-v33.json'));
const classify=o=>{
 const type=String(o.type||'').toUpperCase(),name=String(o.name||'').toUpperCase();
 if(/STUD|STALLION|INTEGRATED BREEDING/.test(type)||/\bSTUD\b/.test(name))return 'stud';
 if(/FARM|NURSERY/.test(type))return 'farm';
 if(/RACING STABLE|OWNERSHIP STABLE/.test(type))return 'stable';
 return '';
};
test('Facilities PREVIEW is a separate one-screen list + persistent right inspector, not existing Office mutation',()=>{
 assert.match(page,/READ-ONLY DESIGN PREVIEW/);
 assert.match(page,/FACILITY REGISTER/);
 assert.match(page,/OPERATIONS INSPECTOR/);
 assert.match(page,/class="workspace"/);
 assert.match(page,/id="rows"/);
 assert.match(page,/id="details"/);
 assert.match(page,/id="filters"/);
 assert.match(page,/id="search"/);
 assert.match(page,/data-filter="track"/);
 assert.match(page,/data-filter="development"/);
 assert.match(page,/class="scenario-title"/);
 assert.match(page,/ONE FACILITY · ONE PROFIT CENTER/);
 assert.doesNotMatch(page,/localStorage\.setItem|fetch\([^)]*,\s*\{method:\s*['"]POST/);
});
test('Founding institution list is derived from the same 37 approved organizations',()=>{
 assert.equal(dir.organizations.length,37);
 const types=dir.organizations.map(classify);
 assert.equal(types.filter(t=>t==='stud').length,5);
 assert.equal(types.filter(t=>t==='farm').length,15);
 assert.equal(types.filter(t=>t==='stable').length,10);
 assert.equal(types.filter(Boolean).length,30);
 assert.match(page,/fetch\('\/data\/wtw-1999-founding-directory-v1\.json'/);
 assert.match(page,/source\.organizations\.length!==37/);
 assert.match(page,/rows\.length!==31/);
 assert.match(page,/classify\(o\)/);
 assert.match(page,/NO BARN|NOT CERTIFIED|NOT ASSESSED/);
});
test('Belmont trainer barn is conspicuously a concept; physical location T-0002 and ownership remain distinct',()=>{
 const belmont=geo.tracks.find(t=>t.id==='T-0002');
 assert.equal(belmont.name,'Belmont Park');
 assert.equal(belmont.country,'USA');
 assert.match(page,/Belmont Park — Trainer Barn Example/);
 assert.match(page,/trackId:'T-0002'/);
 assert.match(page,/HOST TRACK '\+o\.trackId/);
 assert.match(page,/NO BELMONT BARN, STAFF OR HORSES CREATED/);
 assert.match(page,/Horse owner/);
 assert.match(page,/Horse trainer/);
 assert.match(page,/Actual horse residence/);
 assert.match(page,/Facility operator/);
 assert.match(page,/Landowner \/ host/);
 assert.match(page,/Separate operator agreement required/);
 assert.match(page,/Facility F-ID PENDING/);
});
test('Horse-effect examples are bounded and explicitly NOT engine-authoritative',()=>{
 assert.match(page,/Recovery efficiency/);
 assert.match(page,/Avoidable setbacks · relative/);
 assert.match(page,/Typical \/ adequate/);
 assert.match(page,/Neglected \/ crowded/);
 assert.match(page,/ILLUSTRATIVE HORSE-EFFECT SCENARIO/);
 assert.match(page,/NOT calibrated engine outputs/);
 assert.match(page,/SEPARATE SERVICE \/ VENUE REQUIRED/);
 assert.match(page,/Operating profit/);
 assert.match(page,/AI competition/);
});
